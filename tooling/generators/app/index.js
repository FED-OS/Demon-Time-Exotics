#!/usr/bin/env node
/**
 * tooling/generators/app/index.js — DTE app scaffolder.
 *
 * Stamps out a brand-new app workspace under apps/ with the full
 * DTE starter set: package.json (workspace deps, @dte/shared), a
 * self-contained tsconfig extending the repo base, a Vite config
 * using @dte/config-vite presets, an index.html shell with the
 * brand topbar/hero skeleton, a styles.css preloaded with brand
 * tokens, and a src/ scaffold (main.ts, lib/, components/, pages/,
 * hooks/ barrels).
 *
 * Usage:
 *   node tooling/generators/app/index.js <name> [--type web] [--dry-run]
 *
 * Types:
 *   web      vanilla TS + Vite surface (default — same family as landing)
 *
 * The generator refuses to overwrite an existing directory and
 * prints the follow-up steps (pnpm install + dev commands).
 */

import { mkdir, writeFile, access, constants } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "../../..");
const DRY = process.argv.includes("--dry-run");

const args = process.argv.slice(2).filter((a) => !a.startsWith("--"));
function flagValue(key) {
  const hit = process.argv.find((a) => a.startsWith(`--${key}=`));
  return hit ? hit.split("=").slice(1).join("=") : null;
}

function pascal(input) {
  return input
    .replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))
    .replace(/^./, (c) => c.toUpperCase());
}
function kebab(input) {
  return input.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

