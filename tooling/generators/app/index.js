function tplMain(name) {
  return `import { CHANNEL, CHANNEL_STATS } from "@dte/shared";
import { initCounters, initHub } from "./lib/index.js";

/**
 * ${name} — entry point. Keep it thin: data from @dte/shared, DOM
 * wiring in lib/, structure in index.html.
 */
const statsHost = document.querySelector<HTMLElement>("[data-stats]");
if (statsHost) initCounters(statsHost);

const hubHost = document.querySelector<HTMLElement>("[data-hub]");
if (hubHost) initHub(hubHost);

console.info(
  "%c😈 DEMON TIME EXOTICS — ${name}",
  "color:#ff5e1a;font-weight:bold",
  CHANNEL.name,
  CHANNEL_STATS
);
`;
}

function tplLib() {
  return `import { CHANNEL_STATS, PLATFORMS, formatCompact } from "@dte/shared";

/** Animated counters for the hero stats block (matches landing). */
export function initCounters(host: HTMLElement) {
  const counters = host.querySelectorAll<HTMLElement>("[data-count]");
  counters.forEach((el) => {
    const target = Number(el.dataset.count ?? "0");
    el.textContent = formatCompact(target);
  });
}

/** Platform hub grid from the shared platform registry. */
export function initHub(host: HTMLElement) {
  for (const platform of PLATFORMS) {
    const card = document.createElement("a");
    card.className = "hub-card";
    card.href = platform.url;
    card.target = "_blank";
    card.rel = "noopener noreferrer";
    card.innerHTML = \`<span class="icon">\${platform.icon}</span>
      <span class="name">\${platform.name}</span>
      <span class="note">\${platform.note ?? ""}</span>\`;
    host.append(card);
  }
}

export { CHANNEL_STATS };
`;
}

function tplBarrel(dirName) {
  return `// ${dirName} barrel — generated by @dte/gen-app.
`;
}

/* ── Generator ─────────────────────────────────────────────── */

const FILES = (name) => [
  { path: `apps/${kebab(name)}/package.json`, body: tplPackageJson(name) },
  { path: `apps/${kebab(name)}/tsconfig.json`, body: tplTsconfig() },
  { path: `apps/${kebab(name)}/vite.config.ts`, body: tplViteConfig(name) },
  { path: `apps/${kebab(name)}/index.html`, body: tplIndexHtml(name) },
  { path: `apps/${kebab(name)}/src/styles/styles.css`, body: tplStyles() },
  { path: `apps/${kebab(name)}/src/main.ts`, body: tplMain(name) },
  { path: `apps/${kebab(name)}/src/lib/index.ts`, body: tplLib() },
  { path: `apps/${kebab(name)}/src/components/index.ts`, body: tplBarrel("components") },
  { path: `apps/${kebab(name)}/src/pages/index.ts`, body: tplBarrel("pages") },
  { path: `apps/${kebab(name)}/src/hooks/index.ts`, body: tplBarrel("hooks") }
];

async function main() {
  const rawName = args[0];
  if (!rawName || process.argv.includes("--help")) {
    console.log(`Usage: node tooling/generators/app/index.js <name> [--type web] [--dry-run]

  <name>   app name (PascalCase or kebab-case; "@dte/<kebab>" is the package name)
  --type   only "web" is currently generated (vanilla TS + Vite starter)
  --dry-run  print the plan without writing files`);
    process.exit(rawName ? 0 : 1);
  }

  const type = flagValue("type") ?? "web";
  if (type !== "web") {
    console.error(`Unknown type "${type}" — only "web" starters are generated for now.`);
    console.error("Tauri/Electron/Expo surfaces involve native toolchains; copy the");
    console.error("existing apps/tauri, apps/electron or apps/mobile as templates instead.");
    process.exit(1);
  }

  const name = pascal(rawName);
  const appDir = `apps/${kebab(name)}`;
  const dirAbs = path.join(ROOT, appDir);

  console.log("");
  console.log("😈 DTE app generator");
  console.log(`   name:  @dte/${kebab(name)} (${name})`);
  console.log(`   type:  ${type}`);
  console.log(`   dir:   ${appDir}/ (10 files)`);
  console.log("");

  try {
    await access(dirAbs, constants.F_OK);
    console.error(`💥 ${appDir} already exists — refusing to overwrite.`);
    process.exit(1);
  } catch {
    /* not there — good */
  }

  const plan = FILES(name);
  if (DRY) {
    for (const file of plan) {
      console.log(`  would write ${file.path} (${file.body.length} bytes)`);
    }
    return;
  }

  for (const file of plan) {
    const abs = path.join(ROOT, file.path);
    await mkdir(path.dirname(abs), { recursive: true });
    await writeFile(abs, file.body);
    console.log(`✅ ${file.path}`);
  }

  console.log("");
  console.log("── next ───────────────────────────────────────");
  console.log("  pnpm install                     # link the new workspace");
  console.log(`  pnpm --filter @dte/${kebab(name)} dev   # start the dev server`);
  console.log(`  pnpm --filter @dte/${kebab(name)} build  # ship a dist/`);
  console.log("───────────────────────────────────────────────");
  console.log(`\n🔥 ${name} scaffolded. Make it messy.`);
}

main().catch((error) => {
  console.error("app generator crashed:", error);
  process.exit(1);
});
